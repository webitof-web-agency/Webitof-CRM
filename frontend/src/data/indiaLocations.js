/**
 * Get cities array for a given state name
 * @param {string} stateName
 * @returns {string[]}
 */
export function getCitiesByState(stateName) {
  const found = INDIA_STATES.find(
    (s) => s.value === stateName || s.label === stateName
  );
  return found ? found.cities : [];
}

/**
 * Get state code for a given state name
 * @param {string} stateName
 * @returns {string|null}
 */
export function getStateCode(stateName) {
  const found = INDIA_STATES.find(
    (s) => s.value === stateName || s.label === stateName
  );
  return found ? found.code : null;
}

