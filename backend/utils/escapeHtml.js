// Escapes text that comes from records (titles, vendor names, remarks) before it is placed
// inside an HTML email, so stored markup cannot be injected into mail sent to clients.
function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

module.exports = { escapeHtml };
